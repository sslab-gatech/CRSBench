#!/bin/bash
set -ex

# Already in $SRC/libtiff
# Use separate prefix to avoid ASAN artifact conflicts from $WORK

export PIN_ROOT=/opt/pin
export BINARY_RTS=/opt/binary-rts
export PINTOOLS_RTS=$BINARY_RTS/pintools-rts
export PIN_LISTENER_DIR=$PINTOOLS_RTS/pin_listener
RTS_ON=${RTS_ON:-0}
SNAPSHOT_RTS=$(test -d $PIN_ROOT && echo 1 || echo 0)
echo "SNAPSHOT_RTS $SNAPSHOT_RTS RTS_ON $RTS_ON"

cd $SRC/libtiff

# Use a separate prefix for test dependencies (not $WORK which has ASAN artifacts)
TEST_PREFIX="$SRC/test_deps"
mkdir -p "$TEST_PREFIX/lib" "$TEST_PREFIX/include"

# Build zlib (only on first run)
if [ ! -f "$TEST_PREFIX/lib/libz.a" ]; then
    pushd "$SRC/zlib"
    # Configure only if not yet configured (zlib.pc is generated by configure)
    # Note: Cannot check Makefile - zlib ships with a stub Makefile that just prints "run configure first"
    if [ ! -f zlib.pc ]; then
        ./configure --static --prefix="$TEST_PREFIX"
    fi
    make -j$(nproc) CFLAGS="-fPIC"
    make install
    popd
fi

# Build libjpeg-turbo (only on first run)
if [ ! -f "$TEST_PREFIX/lib/libjpeg.a" ]; then
    pushd "$SRC/libjpeg-turbo"
    [ -f Makefile ] || cmake . -DCMAKE_INSTALL_PREFIX=$TEST_PREFIX -DENABLE_STATIC=on -DENABLE_SHARED=off -DCMAKE_C_FLAGS=""
    make -j$(nproc)
    make install
    popd
fi

# Build libjbig (only on first run)
if [ ! -f "$TEST_PREFIX/lib/libjbig.a" ]; then
    pushd "$SRC/jbigkit"
    if [ "$ARCHITECTURE" = "i386" ]; then
        echo "#!/bin/bash" > gcc
        echo "clang -m32 \$*" >> gcc
        chmod +x gcc
        PATH=$PWD:$PATH make lib
    else
        make lib CC="clang" CFLAGS="-O2"
    fi
    cp "$SRC"/jbigkit/libjbig/*.a "$TEST_PREFIX/lib/"
    cp "$SRC"/jbigkit/libjbig/*.h "$TEST_PREFIX/include/"
    popd
fi

if [ "$ARCHITECTURE" != "i386" ]; then
    apt-get install -y liblzma-dev 2>/dev/null || true
fi

COVERAGE_DIR="/tmp/libtiff_coverage"
OUTPUT_DIR="/tmp/libtiff_output"

# Build libtiff (only configure on first run)
if [ ! -f Makefile ]; then
    EXTRA_CMAKE_FLAGS=""
    if [[ $SNAPSHOT_RTS -eq 1 ]]; then
        # Append -fno-inline to prevent inlining, needed for Pin function tracing
        export CFLAGS="${CFLAGS:-} -fno-inline"
        export CXXFLAGS="${CXXFLAGS:-} -fno-inline"
        EXTRA_CMAKE_FLAGS="-DENABLE_PIN_LISTENER=ON -DCMAKE_BUILD_TYPE=Debug"
    fi
    cmake . -DCMAKE_INSTALL_PREFIX=$TEST_PREFIX -DBUILD_SHARED_LIBS=off \
        -DCMAKE_C_FLAGS="-I$TEST_PREFIX/include" \
        -DCMAKE_PREFIX_PATH=$TEST_PREFIX \
        ${EXTRA_CMAKE_FLAGS}
fi
make -j$(nproc)
make install

# First run with Pin: trace tests and collect coverage
if [[ $SNAPSHOT_RTS -eq 1 && ! -d "$COVERAGE_DIR" ]]; then
    mkdir -p "$COVERAGE_DIR"

    echo ""
    echo "=== Running tests under Pin with coverage tracing ==="

    # Run tests under Pin with coverage tracing
    # -dump_on_exit 1 is needed because libtiff uses standalone test executables
    TEST_EXIT=0
    $PIN_ROOT/pin \
        -follow_execv \
        -t $PINTOOLS_RTS/obj-intel64/functrace.so \
        -runtime_dump \
        -logdir "$COVERAGE_DIR" \
        -libs 1 \
        -follow_child 1 \
        -dump_on_exit 1 \
        -- ctest --output-on-failure || TEST_EXIT=$?

    echo ""
    echo "=== Coverage Results ==="
    echo "Coverage directory: $COVERAGE_DIR"
    ls -la "$COVERAGE_DIR" | head -20

    # Convert coverage to CSV
    echo ""
    echo "=== Converting coverage to CSV ==="
    mkdir -p "$OUTPUT_DIR"

    cd $BINARY_RTS/binaryrts/cli
    poetry run binaryrts convert \
        -i "$COVERAGE_DIR" \
        --regex '.*libtiff.*|.*/tif_.*|.*/tools/.*|.*/test/.*' \
        --repo "$SRC/libtiff" \
        -o "$OUTPUT_DIR" \
        cpp --ctest

    echo ""
    echo "=== Output files ==="
    ls -la "$OUTPUT_DIR"

    exit $TEST_EXIT
fi

# RTS mode: select tests based on patch
if [[ $RTS_ON -eq 1 ]]; then
    SELECTION_DIR="/tmp/selection"
    rm -rf "$SELECTION_DIR"

    PATCH=/tmp/patch.diff
    test -f $PATCH

    echo "=== Selecting tests based on patch ==="
    cd $BINARY_RTS/binaryrts/cli
    poetry run binaryrts select \
        --repo "$SRC/libtiff" \
        --diff "$PATCH" \
        --repo-state new \
        -o "$SELECTION_DIR" \
        cpp \
        --lookup "$OUTPUT_DIR/function-lookup.csv" \
        --traces "$OUTPUT_DIR/test-function-traces.csv"

    INCLUDED=$(cat "$SELECTION_DIR/included.txt" 2>/dev/null | grep -v '^$' | wc -l)
    EXCLUDED=$(cat "$SELECTION_DIR/excluded.txt" 2>/dev/null | grep -v '^$' | wc -l)
    echo "Selected tests: $INCLUDED"
    echo "Excluded tests: $EXCLUDED"

    cd "$SRC/libtiff"

    if [[ "$INCLUDED" -eq 0 ]]; then
        echo "No tests selected - all tests excluded!"
        exit 0
    elif [[ "$EXCLUDED" -eq 0 ]]; then
        echo "All tests selected - running without filter"
        ctest --output-on-failure
    else
        # Use binaryrts utils filter to convert included.txt to CTest regex format
        cd $BINARY_RTS/binaryrts/cli
        INCLUDED_TESTS=$(poetry run binaryrts utils filter "$SELECTION_DIR/included.txt" -f ctest 2>/dev/null)
        echo "CTEST_FILTER=$INCLUDED_TESTS"

        cd "$SRC/libtiff"
        if [[ -n "$INCLUDED_TESTS" ]]; then
            ctest -R "$INCLUDED_TESTS" --output-on-failure
        else
            echo "No tests matched filter"
        fi
    fi
else
    # Normal test run (no RTS)
    ctest --output-on-failure
fi

exit $?
