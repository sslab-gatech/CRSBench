"""Run the framework pipeline from one command.

This module defines the high-level pipeline for a framework run. It orchestrates
the execution across several sequential stages. If any stage fails (raises
FrameworkError), the pipeline stops immediately to prevent cascading failures
and pollution of the environment.

Pipeline Flow:
  1. Config Loading: Validate and normalize cfg.json.
  2. Rendering: Generate suite/CRS variants and validate the experiment YAML.
  3. Infrastructure: Stop stale workers and prepare local Valkey.
  4. Readiness: Verify the LLM host and each selected model through Caddy.
  5. Execution: Archive the inputs and launch native CRSBench commands in tmux.
  6. Convenience reports: Produce two CSV views from CRSBench artifacts.
  7. Cleanup: Remove only manifest-tracked transient files generated by the run.

Cleanup is guaranteed via a `finally` block using the Manifest system.
"""

from __future__ import annotations

import argparse
import json
import logging  # noqa: TID251 - standalone wrapper configures stdlib logging
import shutil
import sys
from dataclasses import replace
from datetime import datetime
from pathlib import Path

FRAMEWORK_DIR = Path(__file__).resolve().parent
REPO_ROOT = FRAMEWORK_DIR.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from framework import (  # noqa: E402
    benchmarks,
    caddy,
    config,
    crs,
    experiment,
    results,
    services,
)
from framework.cleanup import Manifest  # noqa: E402
from framework.errors import FrameworkError  # noqa: E402

log = logging.getLogger("framework")


def _generate_csvs(
    experiment_dir: Path, benchmarks_dir: Path, output_dir: Path, label: str
) -> None:
    try:
        csv_paths = results.parse_experiment(experiment_dir, benchmarks_dir, output_dir)
        log.info("result CSVs: %s and %s", *csv_paths)
    except Exception as exc:
        log.warning("could not create %s CSVs: %s", label, exc)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=FRAMEWORK_DIR / "cfg.json")
    parser.add_argument(
        "--retry",
        type=Path,
        help="resume an archived experiment YAML and retry failed trials",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="run checks and generate + validate files, but do not start services",
    )
    return parser.parse_args(argv)


def _experiment_name(data: dict) -> str:
    section = data.get("experiment")
    name = section.get("name") if isinstance(section, dict) else None
    if not isinstance(name, str) or not name.strip():
        raise FrameworkError("retry experiment is missing experiment.name")
    name = name.strip()
    if not config.SAFE_NAME.fullmatch(name):
        raise FrameworkError("retry experiment contains an unsafe experiment.name")
    return name


def _retry_llm_settings(
    data: dict, experiment_yaml: Path
) -> tuple[str, tuple[str, ...]]:
    """Read generic wrapper metadata, with a fallback for older DiscVer runs."""
    metadata_path = experiment_yaml.parent / "support" / "framework.json"
    if metadata_path.is_file():
        try:
            metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise FrameworkError(
                f"cannot read retry metadata {metadata_path}: {exc}"
            ) from exc
        if not isinstance(metadata, dict):
            raise FrameworkError(f"retry metadata is not an object: {metadata_path}")
        host = metadata.get("llm_host")
        models = metadata.get("models")
        if (
            not isinstance(host, str)
            or not isinstance(models, list)
            or not all(isinstance(model, str) and model for model in models)
        ):
            raise FrameworkError(f"retry metadata is invalid: {metadata_path}")
        return config.normalize_host(host), tuple(models)

    # Compatibility with archives created before generic wrapper metadata.
    compose = data.get("crs_compose")
    if not isinstance(compose, dict) or not compose:
        raise FrameworkError("retry experiment has no crs_compose services")

    hosts: set[str] = set()
    models: list[str] = []
    for service_name, service in compose.items():
        if service_name == "oss_crs_infra" or not isinstance(service, dict):
            continue
        additional_env = service.get("additional_env")
        if not isinstance(additional_env, dict):
            continue
        raw_url = additional_env.get("DISCVER_LLM_URL")
        raw_model = additional_env.get("DISCVER_LLM_MODEL")
        if raw_url is None and raw_model is None:
            continue
        if not isinstance(raw_url, str) or not raw_url.strip():
            raise FrameworkError(
                f"retry CRS {service_name!r} has no valid DISCVER_LLM_URL"
            )
        if not isinstance(raw_model, str) or not raw_model.strip():
            raise FrameworkError(
                f"retry CRS {service_name!r} has no valid DISCVER_LLM_MODEL"
            )
        hosts.add(config.normalize_host(raw_url))
        model = raw_model.strip()
        if model not in models:
            models.append(model)

    if not hosts or not models:
        raise FrameworkError(
            "retry experiment does not record DISCVER_LLM_URL and "
            "DISCVER_LLM_MODEL in crs_compose.additional_env"
        )
    if len(hosts) != 1:
        raise FrameworkError(
            f"retry experiment records multiple DISCVER LLM endpoints: {sorted(hosts)}"
        )
    return next(iter(hosts)), tuple(models)


def _restore_support_file(
    source: Path,
    target: Path,
    manifest: Manifest,
    *,
    description: str,
) -> None:
    """Restore one archived support file without replacing an existing file."""
    if target.exists():
        if not target.is_file():
            raise FrameworkError(
                f"existing {description} is not a regular file: {target}"
            )
        if source.is_file() and source.read_bytes() != target.read_bytes():
            raise FrameworkError(
                f"existing {description} conflicts with retry archive: {target}"
            )
        return
    if not source.is_file():
        raise FrameworkError(
            f"retry support file is missing: {source}; "
            f"restore the referenced {description} manually"
        )
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)
    manifest.add(target)


def _restore_retry_support(
    cfg: config.RunnerConfig,
    experiment_yaml: Path,
    data: dict,
    manifest: Manifest,
) -> None:
    """Restore transient suite and registry files archived by a normal run."""
    support_dir = experiment_yaml.parent / "support"
    experiment_section = data.get("experiment", {})
    suite = experiment_section.get("benchmark_suite")
    if not isinstance(suite, str) or not suite:
        raise FrameworkError("retry experiment is missing experiment.benchmark_suite")
    suite_relative = Path(f"{suite}.yaml")
    if suite_relative.is_absolute() or ".." in suite_relative.parts:
        raise FrameworkError("retry experiment contains an unsafe benchmark_suite")
    suite_target = (cfg.suites_dir / suite_relative).resolve()
    if not suite_target.is_relative_to(cfg.suites_dir.resolve()):
        raise FrameworkError("retry benchmark suite escapes the configured suite root")
    _restore_support_file(
        support_dir / "benchmark-suite.yaml",
        suite_target,
        manifest,
        description="benchmark suite",
    )

    compose = data.get("crs_compose")
    if not isinstance(compose, dict) or not compose:
        raise FrameworkError("retry experiment has no crs_compose services")
    for crs_name in compose:
        if crs_name == "oss_crs_infra":
            continue
        if not isinstance(crs_name, str) or not config.SAFE_NAME.fullmatch(crs_name):
            raise FrameworkError(
                f"retry experiment contains unsafe CRS name: {crs_name!r}"
            )
        target = cfg.registry_dir / f"{crs_name}.yaml"
        source = support_dir / "registry" / f"{crs_name}.yaml"
        _restore_support_file(
            source,
            target,
            manifest,
            description=f"CRS registry entry for {crs_name}",
        )


def retry_stages(cfg: config.RunnerConfig, retry_path: Path, manifest: Manifest) -> int:
    experiment_yaml = retry_path.expanduser().resolve()
    data = experiment.load_experiment(experiment_yaml)
    experiment_name = _experiment_name(data)
    llm_host, llm_models = _retry_llm_settings(data, experiment_yaml)
    storage = data.get("storage")
    runtime = data.get("runtime")
    experiment_filestore = (
        storage.get("experiment_filestore") if isinstance(storage, dict) else None
    )
    if not isinstance(experiment_filestore, str) or not experiment_filestore:
        raise FrameworkError("retry experiment is missing storage.experiment_filestore")
    if not isinstance(runtime, dict):
        raise FrameworkError("retry experiment is missing its runtime section")

    experiment_data_dir = Path(experiment_filestore).expanduser().resolve()
    results_dir = experiment_data_dir.parent
    retry_id = datetime.now().strftime("retry-%Y%m%d-%H%M%S-%f")
    retry_cfg = replace(
        cfg,
        run_id=experiment_name,
        llm_host=llm_host,
        llm_models=llm_models,
        results_dir=results_dir,
        tmux_session=f"{experiment_name}-{retry_id}",
    )

    services.require_tmux()
    _restore_retry_support(retry_cfg, experiment_yaml, data, manifest)
    services.clear_existing_workers()
    services.check_valkey_connection(runtime.get("redis_host"))
    caddy.run_caddy_checks(retry_cfg, REPO_ROOT)

    archive_dir = experiment_yaml.parent
    queue_model = None
    queue_model_path = archive_dir / "support" / "queue-model.txt"
    if queue_model_path.is_file():
        queue_model = queue_model_path.read_text(encoding="utf-8").strip()
        if queue_model not in {"flat", "per-experiment"}:
            raise FrameworkError(f"unsupported archived queue model: {queue_model!r}")
    retry_dir = archive_dir / "retries" / retry_id
    retry_dir.mkdir(parents=True, exist_ok=False)
    logs_dir = retry_dir / "logs"
    exit_path = retry_dir / "runner.exit"
    session_started = False
    failure: BaseException | None = None
    code: int | None = None
    try:
        services.launch_tmux(
            retry_cfg,
            REPO_ROOT,
            experiment_yaml,
            logs_dir=logs_dir,
            exit_path=exit_path,
            retry=True,
            queue_model=queue_model,
        )
        session_started = True
        services.log_monitoring_commands(retry_cfg, logs_dir=logs_dir)
        code = services.wait_for_runner(retry_cfg, exit_path=exit_path)
    except BaseException as exc:
        failure = exc
    finally:
        if session_started:
            services.stop_session(retry_cfg)
    _generate_csvs(
        experiment_data_dir / experiment_name,
        retry_cfg.benchmarks_dir,
        retry_dir / "csv",
        "retry",
    )
    if failure is not None:
        raise failure
    assert code is not None
    if code != 0:
        log.error("retry runner exited with code %d; see %s", code, logs_dir)
    return code


def run_stages(cfg: config.RunnerConfig, manifest: Manifest, dry_run: bool) -> int:
    benchmarks.check_benchmarks(cfg, REPO_ROOT)
    suite = benchmarks.write_suite(cfg, REPO_ROOT, manifest)
    variants = crs.prepare_variants(cfg, REPO_ROOT, manifest)
    experiment_yaml = experiment.write_experiment(
        cfg,
        REPO_ROOT,
        suite,
        variants,
        manifest,
    )
    rendered = experiment.load_experiment(experiment_yaml)
    runtime = rendered.get("runtime")
    if not isinstance(runtime, dict):
        raise FrameworkError("generated experiment is missing runtime")
    if dry_run:
        caddy.run_caddy_checks(cfg, REPO_ROOT)
        log.info(
            "dry run: generated %d files, not starting services", len(manifest.paths)
        )
        return 0

    services.require_local_services()
    services.clear_existing_workers()
    services.prepare_local_valkey(REPO_ROOT, runtime.get("redis_host"))
    caddy.run_caddy_checks(cfg, REPO_ROOT)
    archived = experiment.archive_experiment(cfg, experiment_yaml, suite, variants)
    log.info("archived reproducible config at %s", archived)
    session_started = False
    failure: BaseException | None = None
    code: int | None = None
    try:
        services.launch_tmux(cfg, REPO_ROOT, experiment_yaml, queue_model="flat")
        session_started = True
        services.log_monitoring_commands(cfg)
        code = services.wait_for_runner(cfg)
    except BaseException as exc:
        failure = exc
    finally:
        if session_started:
            services.stop_session(cfg)
    _generate_csvs(
        cfg.experiment_data_dir / cfg.run_id,
        cfg.benchmarks_dir,
        cfg.run_dir / "csv",
        "result",
    )
    log.info("CRS logs are under %s", cfg.experiment_data_dir / cfg.run_id)
    if failure is not None:
        raise failure
    assert code is not None
    if code != 0:
        log.error("runner exited with code %d; see %s", code, cfg.logs_dir)
    return code


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s"
    )
    args = parse_args(argv)
    manifest = Manifest()
    try:
        cfg = config.load_config(args.config)
        log.info("run id %s", cfg.run_id)
        if args.retry is not None:
            if args.dry_run:
                raise FrameworkError("--retry and --dry-run cannot be used together")
            return retry_stages(cfg, args.retry, manifest)
        return run_stages(cfg, manifest, args.dry_run)
    except (FrameworkError, OSError) as exc:
        log.error("FAILED: %s", exc)
        return 1
    finally:
        removed = manifest.cleanup()
        log.info("cleanup: removed %d generated files", len(removed))


if __name__ == "__main__":
    sys.exit(main())
